// Third-party notices: which licenses may ship, and how the notices file is written.
// Used by scripts/notices.mjs; pure functions, so they are unit-tested.
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Licenses a shipped dependency may have (SPDX ids). Anything else fails the
 * release. Python-2.0 is listed explicitly: the permissive PSF license of
 * argparse, which js-yaml depends on.
 */
export const PERMISSIVE_LICENSES = [
  'MIT',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  '0BSD',
  'Python-2.0',
]

/**
 * Whether an SPDX expression is permissive: every part joined by AND must be,
 * and at least one alternative joined by OR.
 */
export function isPermissive(expression, allowed = PERMISSIVE_LICENSES) {
  const text = String(expression ?? '')
    .replace(/[()]/g, ' ')
    .trim()
  if (!text) return false
  return text
    .split(/\s+OR\s+/i)
    .some((alternative) =>
      alternative.split(/\s+AND\s+/i).every((part) => allowed.includes(part.trim())),
    )
}

/**
 * Flattens `pnpm licenses list --json` output (grouped by license) into one
 * entry per package version, sorted by name. Workspace packages are left out.
 */
export function packagesFromPnpm(report) {
  const packages = []
  for (const group of Object.values(report)) {
    for (const item of group) {
      if (item.name.startsWith('@loam/')) continue
      item.versions.forEach((version, index) => {
        packages.push({
          name: item.name,
          version,
          license: item.license,
          path: item.paths[index] ?? item.paths[0] ?? null,
          homepage: item.homepage ?? null,
        })
      })
    }
  }
  return packages.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
}

/** Packages whose license may not ship. */
export function disallowed(packages, allowed = PERMISSIVE_LICENSES) {
  return packages.filter((pkg) => !isPermissive(pkg.license, allowed))
}

const LICENSE_FILE = /^(licen[cs]e|copying)(\.(md|txt|markdown))?$/i

/** The license text a package ships, or null when it has no license file. */
export function licenseText(packageDir) {
  if (!packageDir || !existsSync(packageDir)) return null
  const name = readdirSync(packageDir)
    .filter((file) => LICENSE_FILE.test(file))
    .sort()[0]
  return name ? readFileSync(join(packageDir, name), 'utf8').replace(/\r\n/g, '\n').trim() : null
}

/**
 * THIRD_PARTY_NOTICES.md: every bundled package with its license text, then
 * the components downloaded only at the user's request.
 */
export function renderNotices(packages, downloads) {
  const lines = [
    '# Third-party notices',
    '',
    'Loam includes the following open-source software. Each is listed with its version, license and license text.',
    '',
    'This file is generated by `pnpm notices` from the production dependency tree; do not edit it by hand.',
    '',
    '## Included in Loam',
    '',
    '| Package | Version | License |',
    '| --- | --- | --- |',
    ...packages.map((pkg) => `| ${pkg.name} | ${pkg.version} | ${pkg.license} |`),
    '',
    'The Electron runtime also ships the licenses of Chromium and its components in `LICENSES.chromium.html`, next to `Loam.exe`.',
    '',
  ]
  for (const pkg of packages) {
    lines.push(`### ${pkg.name} ${pkg.version}`, '', `License: ${pkg.license}`, '')
    const text =
      pkg.text ??
      `No license file is included in the package; its declared license is ${pkg.license}.`
    lines.push('```text', text, '```', '')
  }
  lines.push(
    '## Downloaded only at your request (not included)',
    '',
    'The optional local helpers are off by default. When you choose to download the model in Settings, Loam fetches these files from their publishers. They are not part of the Loam download or installer.',
    '',
    '| Component | Version | License | Source |',
    '| --- | --- | --- | --- |',
    ...downloads.map(
      (item) => `| ${item.name} | ${item.version} | ${item.license} | ${item.source} |`,
    ),
    '',
  )
  return `${lines.join('\n')}`
}
